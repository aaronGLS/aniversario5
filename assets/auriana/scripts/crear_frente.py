def crear_sprite() -> Image.Image:
    """Dibuja la cuadricula original sin reescalado ni interpolacion."""
    imagen = Image.new("RGBA", (TAMANO, TAMANO), (0, 0, 0, 0))
    imagen.putdata([PALETA[simbolo] for fila in PIXELES for simbolo in fila])
    return imagen


def main() -> None:
    carpeta = Path(__file__).resolve().parent.parent
    imagen = crear_sprite()
    original = carpeta / "frames" / "reposo" / "frente" / "frame_000.png"
    previa = carpeta / "vistas_previas" / "reposo" / "frente" / "frame_000.png"
    original.parent.mkdir(parents=True, exist_ok=True)
    previa.parent.mkdir(parents=True, exist_ok=True)
    imagen.save(original, optimize=True)
    lado_previa = TAMANO * ESCALA_PREVIA
    imagen.resize(
        (lado_previa, lado_previa), Image.Resampling.NEAREST
    ).save(previa, optimize=True)
    print(f"PNG 64 x 64: {original}")
    print(f"Vista previa {lado_previa} x {lado_previa}: {previa}")


if __name__ == "__main__":
    main()
